fn render_rust_records(output: &mut String, catalog: &ContractCatalogV1) {
    for record in &catalog.records {
        writeln!(
            output,
            "\n#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n\
             #[serde(deny_unknown_fields)]\n\
             pub struct {} {{",
            record.name
        )
        .expect("writing to a String cannot fail");
        for field in &record.fields {
            writeln!(
                output,
                "    pub {}: {},",
                field.name,
                rust_type(field.field_type)
            )
            .expect("writing to a String cannot fail");
        }
        output.push_str("}\n");
    }
}

fn render_typescript_records(output: &mut String, catalog: &ContractCatalogV1) {
    for record in &catalog.records {
        writeln!(output, "\nexport interface {} {{", record.name)
            .expect("writing to a String cannot fail");
        for field in &record.fields {
            writeln!(
                output,
                "  {}: {};",
                field.name,
                typescript_type(field.field_type)
            )
            .expect("writing to a String cannot fail");
        }
        output.push_str("}\n");
    }
}

