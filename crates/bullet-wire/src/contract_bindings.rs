#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum PinnedContract {
    SchemaBundle,
    InvariantRegistry,
    PolicySnapshot,
    CanonicalGolden,
}

impl PinnedContract {
    fn identity(self) -> (&'static str, &'static str) {
        match self {
            Self::SchemaBundle => ("schema.bundle", SCHEMA_BUNDLE_HASH),
            Self::InvariantRegistry => ("invariant.registry", INVARIANT_REGISTRY_HASH),
            Self::PolicySnapshot => ("policy.snapshot", POLICY_SNAPSHOT_HASH),
            Self::CanonicalGolden => ("golden.cross-language", CANONICAL_GOLDEN_HASH),
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ContractPinError {
    document: &'static str,
}

impl ContractPinError {
    #[must_use]
    pub const fn reason_code(&self) -> &'static str {
        "UNPINNED_CONTRACT"
    }

    #[must_use]
    pub const fn document(&self) -> &'static str {
        self.document
    }
}

impl std::fmt::Display for ContractPinError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            formatter,
            "{} bytes do not match the pinned identity",
            self.document
        )
    }
}

impl std::error::Error for ContractPinError {}

pub fn verify_pinned_contract(
    contract: PinnedContract,
    bytes: &[u8],
) -> Result<(), ContractPinError> {
    let (domain, expected) = contract.identity();
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"bullet-wire.v1\0");
    update_frame(&mut hasher, domain.as_bytes());
    update_frame(&mut hasher, bytes);
    let actual = hasher.finalize().to_hex();
    if actual.as_str() == expected {
        Ok(())
    } else {
        Err(ContractPinError { document: domain })
    }
}

fn update_frame(hasher: &mut blake3::Hasher, bytes: &[u8]) {
    hasher.update(&(bytes.len() as u64).to_le_bytes());
    hasher.update(bytes);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn golden_pin_rejects_any_byte_or_domain_change() {
        verify_pinned_contract(
            PinnedContract::CanonicalGolden,
            CANONICAL_GOLDEN_JSON.as_bytes(),
        )
        .unwrap();

        let mut changed = CANONICAL_GOLDEN_JSON.as_bytes().to_vec();
        changed.push(b' ');
        let error = verify_pinned_contract(PinnedContract::CanonicalGolden, &changed).unwrap_err();
        assert_eq!(error.reason_code(), "UNPINNED_CONTRACT");
        assert_eq!(error.document(), "golden.cross-language");
        assert!(verify_pinned_contract(
            PinnedContract::SchemaBundle,
            CANONICAL_GOLDEN_JSON.as_bytes(),
        )
        .is_err());
    }
}
